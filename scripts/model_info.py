import json
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def model_info():
    weights = (ROOT / "public/alphatiger.onnx").read_bytes()
    model = next(path for path in (ROOT / "ai/models/onnx").glob("*.onnx")
                 if path.read_bytes() == weights)
    manifest = json.loads((ROOT / "ai/models/manifest.json").read_text())
    released = subprocess.check_output(
        ["git", "log", "-1", "--format=%cs", "--", "public/alphatiger.onnx"],
        cwd=ROOT, text=True,
    ).strip()
    assert released, "Commit the browser model before generating its release information"
    return dict(version=model.stem.removeprefix("alphatiger"), released=released,
                estimated_elo=manifest[model.stem]["estimated_elo"])


if __name__ == "__main__":
    info = json.dumps(model_info(), indent=2)
    (ROOT / "public/model-info.js").write_text(
        f"// Generated by scripts/model_info.py from the deployed weights and model records.\nconst ALPHATIGER = {info};\n"
    )
